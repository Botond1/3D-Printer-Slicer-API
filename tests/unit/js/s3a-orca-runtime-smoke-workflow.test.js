test('workflow binds Orca smoke to exact identity, cleanup, and final enforcement', () => {
    const orca = step('orca_cli_smoke');
    const cleanup = step('exact_cleanup');
    const final = step('final_enforcement');
    assert.match(orca, /if: \$\{\{ steps\.runtime_identity\.outcome == 'success' \}\}/);
    assert.match(orca, /continue-on-error: true/);
    assert.match(orca, /EXPECTED_IMAGE_ID: \$\{\{ steps\.image_identity\.outputs\.image_id \}\}/);
    assert.match(orca, /SERVICE_UID: \$\{\{ steps\.runtime_identity\.outputs\.uid \}\}/);
    assert.match(orca, /SERVICE_GID: \$\{\{ steps\.runtime_identity\.outputs\.gid \}\}/);
    assert.match(orca, /node scripts\/i2-orca-runtime-smoke\.js/);
    assert.match(cleanup, /I2_ORCA_PROBE_NAME/);
    assert.match(final, /ORCA_CLI_SMOKE_OUTCOME/);
    assert.match(final, /ORCA_CLI_SMOKE_CLASSIFICATION/);
    assert.match(final, /failures\.push\('orca_cli_smoke_failure'\)/);
    helperContract(SOURCE);
});

test('Orca smoke weakening mutations are rejected by the local contract', async (t) => {
    const mutations = [
        ['network restored', "'--network', 'none'", "'--network', 'bridge'"],
        ['floating image admitted', 'validateImageId(imageId)', 'imageId'],
        ['shell enabled', 'shell: false', 'shell: true'],
        ['root identity admitted', 'numeric <= 0', 'numeric < 0'],
        ['world-writable tmpfs', 'mode=0700', 'mode=0777'],
        ['synthetic slice removed', 'const sliced = runOrca([...slicerArgs, model]',
            'const sliced = runOrca([model]'],
        ['shared command policy bypassed', 'const slicerArgs = buildSlicerCommandArgs(',
            'const slicerArgs = bypassedCommandBuilder('],
        ['placement disabled', "slicerArgs[arrangeIndex + 1] !== '1'",
            "slicerArgs[arrangeIndex + 1] !== '0'"],
        ['orientation restored', "slicerArgs[orientIndex + 1] !== '0'",
            "slicerArgs[orientIndex + 1] !== '1'"],
        ['output bound removed', 'stat.size > 32 * 1024 * 1024', 'false'],
        ['zero extrusion admitted', 'Number(extrusion[1]) > 0', 'Number(extrusion[1]) >= 0'],
        ['model-layer marker removed', ';BEFORE_LAYER_CHANGE', ';IGNORED_LAYER_CHANGE'],
        ['positive extrusion proof bypassed', '!hasPositiveExtrusionMove(prefix)', 'false'],
        ['relative G-code proof removed', "!/^M83(?:\\s|;|$)/m.test(prefix)", 'false'],
        ['native output bound removed', 'maxBuffer: MAX_ORCA_OUTPUT_BYTES', 'maxBuffer: Infinity'],
        ['version assertion removed', 'OrcaSlicer-2\\.3\\.1', 'OrcaSlicer'],
        ['production profile generator bypassed',
            "createRuntimeSlicerProfile(\n        'orca', snapshots.baseConfigFile, 'FDM', 0.2, '20%', workspace)",
            'Promise.resolve(baseProcessProfile)'],
        ['absolute extrusion reset guard removed', "profile.layer_gcode !== ''", 'false'],
        ['relative extrusion guard removed',
            "profile.use_relative_e_distances !== '1'", 'false'],
        ['machine layer reset guard removed',
            "throw new Error('machine_profile_extrusion_contract')", 'return'],
        ['scratch profile containment removed', 'assertScratchContainedPath:', 'unsafeScratchPath:'],
        ['runtime profile containment removed', 'assertContainedPath:', 'unsafeContainedPath:'],
        ['async failure handling removed',
            "void executeSmoke().catch(() => exit(39));", 'void executeSmoke();'],
        ['ownership assertion removed', '    assertOwned(record, containerId, imageId);', '    void record;']
    ];
    for (const [name, from, to] of mutations) await t.test(name, () => {
        assert.ok(SOURCE.includes(from), `missing ${from}`);
        assert.throws(() => helperContract(SOURCE.replace(from, to)));
    });
});
